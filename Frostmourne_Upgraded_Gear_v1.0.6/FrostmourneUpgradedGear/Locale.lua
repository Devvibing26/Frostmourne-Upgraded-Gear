function FUL:GetLanguage()
  local lang = self.db and self.db.language or "enUS"
  if not FUL_LOCALES[lang] then lang = "enUS" end
  return lang
end

function FUL:T(key, ...)
  local lang = self:GetLanguage()
  local value = (FUL_LOCALES[lang] and FUL_LOCALES[lang][key]) or (FUL_LOCALES.enUS and FUL_LOCALES.enUS[key]) or key
  if select("#", ...) > 0 then
    local ok, formatted = pcall(string.format, value, ...)
    if ok then return formatted end
  end
  return value
end
